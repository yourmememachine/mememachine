#!/bin/bash
# up.sh — bring up the Machine PUBLIC TESTNET on a single host.
#
# Thin sequencer over the existing, tested livenet package — it adds
# no new chain logic. See testnet/TESTNET.md for the full phase,
# including labeling rules and what happens after the chain is up.
#
# Safety shape:
#   - Refuses to run unless TESTNET=1 is set in the environment.
#   - Refuses to run in a checkout that already has livenet keys
#     (testnet and livenet never share a checkout or a host dir),
#     unless this script itself generated them on a previous testnet
#     run (marker file below) — that is the resume path: steps whose
#     output already exists are skipped, not regenerated.
#   - Stops at the first failing step (set -e) and says which step.
#     The validators are only boot-enabled AFTER the proof step
#     passes, so a failed bring-up never leaves a broken chain
#     configured to start at every boot.
#
# Usage (on the testnet VPS, from the repo root of the testnet checkout):
#   TESTNET=1 ./testnet/up.sh
set -e

if [ "${TESTNET:-}" != "1" ]; then
  echo "REFUSING: this script brings up the public TESTNET." >&2
  echo "Re-run as: TESTNET=1 ./testnet/up.sh" >&2
  exit 1
fi

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(dirname "$SCRIPT_DIR")"
cd "$ROOT_DIR"

MARKER="livenet/.testnet-generated"
RESUME=0
if [ -f "$MARKER" ]; then
  RESUME=1
  echo "Resuming a previous testnet bring-up (marker $MARKER present); completed steps are skipped."
elif [ -d livenet/keys ] || [ -f livenet/genesis-info.env ]; then
  echo "REFUSING: this checkout already has livenet keys/genesis not generated by this script." >&2
  echo "Use a dedicated testnet checkout (see testnet/TESTNET.md)." >&2
  exit 1
fi

step() { echo; echo "=== up.sh: $1 ==="; }

step "1/7 host gate (fd limits, UDP, disk, RAM)"
./ops/check-host.sh

step "2/7 Agave 2.3.13 toolchain (bin/)"
if [ ! -x bin/agave-validator ]; then
  TAR_OPTIONS=--no-same-owner ./install.sh
fi

step "3/7 test keys (generated here, never leave this host)"
if [ "$RESUME" = 1 ] && [ -d livenet/keys ] && [ -n "$(ls -A livenet/keys 2>/dev/null)" ]; then
  echo "Keys already generated by the previous run — skipping."
else
  ./livenet/generate-keys.sh
  touch "$MARKER"
fi

step "4/7 test genesis"
if [ "$RESUME" = 1 ] && [ -f livenet/genesis-info.env ] && [ -d livenet/ledger ]; then
  echo "Genesis already built by the previous run — skipping."
else
  ./livenet/generate-genesis.sh
fi

step "5/7 validators (systemd units from livenet/) — started, not yet enabled"
# The livenet units hardcode /opt/mememachine; rewrite them to THIS
# checkout so a dedicated testnet checkout (TESTNET.md: ~/mememachine-testnet)
# starts its own validators, never another tree's.
for unit in livenet/mememachine-validator-*.service; do
  sed "s|/opt/mememachine|$ROOT_DIR|g" "$unit" | sudo tee "/etc/systemd/system/$(basename "$unit")" >/dev/null
done
sudo systemctl daemon-reload
for n in 1 2 3; do
  sudo systemctl start "mememachine-validator-$n"
done

step "6/7 proof: consensus + signed transfer"
# systemctl start returns when the process launches, not when the
# RPC opens; wait for validator 1's RPC before running the proof, so
# a slow-but-healthy boot is not failed on timing alone.
echo "Waiting for validator 1 RPC to answer..."
ready=0
for attempt in $(seq 1 60); do
  if [ -x bin/solana ] && bin/solana slot --url http://127.0.0.1:8899 >/dev/null 2>&1; then
    ready=1; break
  fi
  sleep 2
done
[ "$ready" = 1 ] || { echo "ERROR: validator 1 RPC did not answer within 120s." >&2; exit 1; }
./livenet/check-cluster.sh --with-transfer

step "7/7 proof passed — enable the validators at boot"
for n in 1 2 3; do
  sudo systemctl enable "mememachine-validator-$n"
done

echo
echo "Testnet chain is up. Next, per testnet/TESTNET.md:"
echo "  - expose the public RPC (ops/PUBLIC-RPC.md) + start the faucet"
echo "  - deploy the bridge to Solana devnet <-> this testnet (drills!)"
echo "  - deploy LaunchGuard and register the demo launch"
